"""Serve a fine-tuned SVAGA model so the existing SVAGA platform can use it with NO code changes.

SVAGA's local provider talks to Ollama's /api/chat. This server speaks the same protocol on its own port:
  POST /api/chat     -> generated by base model + LoRA adapter (JSON answer extracted if SVAGA asked for JSON)
  everything else    -> forwarded to the real Ollama (so retrieval embeddings, /api/embed, keep working)

Usage (GPU machine or a laptop with a CUDA GPU):
  pip install fastapi uvicorn httpx "transformers>=4.46,<5" peft bitsandbytes accelerate pyyaml lm-format-enforcer
  python serve_svaga_model.py --run RETURN_folder/ftA_qwen25coder_1p5b --port 11500
Then start SVAGA's API with:
  $env:SVAGA_LLM_PROVIDER="ollama"; $env:SVAGA_SCRIPTED_LLM="0"
  $env:OLLAMA_BASE_URL="http://127.0.0.1:11500"; $env:OLLAMA_MODEL="ftA_qwen25coder_1p5b"
  python -m uvicorn svaga_platform.app.main:app --host 127.0.0.1 --port 8003
Add --base_only to serve the same base model without the adapter (for the before/after comparison inside SVAGA).
"""
import argparse, json, re, sys, time
from pathlib import Path

import httpx, torch, uvicorn, yaml
from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse, Response
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
from peft import PeftModel

ap = argparse.ArgumentParser()
ap.add_argument("--run", required=True, help="unzipped RETURN_<run> folder (contains outputs/ and config.yaml)")
ap.add_argument("--port", type=int, default=11500)
ap.add_argument("--ollama", default="http://127.0.0.1:11434", help="real Ollama, for embeddings")
ap.add_argument("--base_only", action="store_true")
ap.add_argument("--max_new_tokens", type=int, default=3000, help="hard cap per answer (SVAGA may ask for more)")
ap.add_argument("--repeat_penalty", type=float, default=1.1, help="1.1 = Ollama's default, as used for the Demo 1 runs; 1.0 = off")
ap.add_argument("--unconstrained", action="store_true",
                help="do NOT force valid JSON while generating (Demo 1's Ollama runs were constrained; use only to reproduce the first run)")
ap.add_argument("--log", default=None, help="JSONL log of every request and raw answer (default: <run>/serve_log_<port>.jsonl)")
a = ap.parse_args()
run = Path(a.run)
sys.path.insert(0, str(Path(__file__).parent))
from svaga_format import render_prompt, load_tokenizer

cfg = yaml.safe_load(open(run / "config.yaml"))
summary = json.load(open(run / "outputs" / "metrics" / "train_summary.json"))
use_ct = summary["use_chat_template"]
dtype = torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
tok = load_tokenizer(cfg["model_id"], cfg.get("revision"))
model = AutoModelForCausalLM.from_pretrained(cfg["model_id"], revision=cfg.get("revision"), torch_dtype=dtype, device_map={"": 0},
    quantization_config=BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4", bnb_4bit_use_double_quant=True, bnb_4bit_compute_dtype=dtype))
if not a.base_only:
    model = PeftModel.from_pretrained(model, str(run / "outputs" / "final_adapter"))
model.eval()
NAME = cfg["run_name"] + ("-base" if a.base_only else "")
LOG = Path(a.log) if a.log else run / f"serve_log_{a.port}.jsonl"
TOKDATA = None
if not a.unconstrained:
    # same idea as Ollama's `format`: only tokens that keep the output valid JSON may be generated
    from lmformatenforcer import JsonSchemaParser
    from lmformatenforcer.integrations.transformers import build_token_enforcer_tokenizer_data, build_transformers_prefix_allowed_tokens_fn
    print("building JSON-constraint tables for the tokenizer (once, can take a minute)...")
    TOKDATA = build_token_enforcer_tokenizer_data(tok)
app = FastAPI(title=f"SVAGA model server: {NAME}")
proxy = httpx.AsyncClient(base_url=a.ollama, timeout=600)


def extract_json(text: str) -> str:
    """Return the first JSON object in the answer, re-serialized as strict JSON. strict=False accepts raw line breaks inside
    strings (a common small-model habit when code sits in a JSON string); prose or code fences around the object are dropped.
    No usable object -> the raw text, so SVAGA records the failure."""
    fenced = re.findall(r"```(?:json)?\s*(\{.*?\})\s*```", text, flags=re.S)
    for cand in fenced + [text[text.find("{"): text.rfind("}") + 1]]:
        try:
            return json.dumps(json.loads(cand, strict=False))
        except Exception:
            continue
    return text


@app.post("/api/chat")
async def chat(req: Request):
    body = await req.json()
    msgs = [{"role": m["role"], "content": m["content"]} for m in body.get("messages", [])]
    wants_json = bool(body.get("format"))
    if isinstance(body.get("format"), dict):
        msgs[-1]["content"] += "\n\nReply with one JSON object matching this JSON schema:\n" + json.dumps(body["format"])
    opts = body.get("options") or {}
    prompt = render_prompt(tok, msgs + [{"role": "assistant", "content": ""}], use_ct)
    ids = tok(prompt, return_tensors="pt", add_special_tokens=not use_ct).to(model.device)
    temp = float(opts.get("temperature", 0.2))
    limit = min(int(opts.get("num_predict", a.max_new_tokens)), a.max_new_tokens)
    extra = {}
    if wants_json and TOKDATA is not None:
        schema = body["format"] if isinstance(body.get("format"), dict) else None
        extra["prefix_allowed_tokens_fn"] = build_transformers_prefix_allowed_tokens_fn(TOKDATA, JsonSchemaParser(schema))
    t0 = time.time()
    with torch.no_grad():
        out = model.generate(**ids, max_new_tokens=limit, do_sample=temp > 0, temperature=max(temp, 1e-5),
                             pad_token_id=tok.pad_token_id, repetition_penalty=float(opts.get("repeat_penalty", a.repeat_penalty)), **extra)
    raw = tok.decode(out[0][ids["input_ids"].shape[1]:], skip_special_tokens=True, clean_up_tokenization_spaces=False)
    text = extract_json(raw) if wants_json else raw
    try:
        with LOG.open("a", encoding="utf-8") as f:
            f.write(json.dumps({"time": time.strftime("%Y-%m-%dT%H:%M:%S"), "model": NAME, "constrained": bool(extra),
                                "seconds": round(time.time() - t0, 1), "new_tokens": int(out.shape[1] - ids["input_ids"].shape[1]),
                                "limit": limit, "json_ok": _is_json(text) if wants_json else None,
                                "system": msgs[0]["content"][:300] if msgs else "", "raw": raw}) + "\n")
    except Exception as e:  # logging must never break serving
        print("log write failed:", e)
    n_in, n_out = int(ids["input_ids"].shape[1]), int(out.shape[1] - ids["input_ids"].shape[1])
    return JSONResponse({"model": NAME, "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ"), "done": True, "done_reason": "stop",
                         "message": {"role": "assistant", "content": text}, "prompt_eval_count": n_in, "eval_count": n_out,
                         "total_duration": int((time.time() - t0) * 1e9), "load_duration": 0})


def _is_json(s: str) -> bool:
    try:
        json.loads(s); return True
    except Exception:
        return False


@app.get("/svaga/health")
async def health():
    return {"model": NAME, "base": cfg["model_id"], "adapter": not a.base_only, "json_constrained": TOKDATA is not None,
            "max_new_tokens": a.max_new_tokens, "repeat_penalty": a.repeat_penalty, "log": str(LOG)}


@app.api_route("/{path:path}", methods=["GET", "POST", "PUT", "DELETE"])
async def forward(path: str, req: Request):
    r = await proxy.request(req.method, "/" + path, content=await req.body(), headers={"content-type": req.headers.get("content-type", "application/json")})
    return Response(r.content, status_code=r.status_code, media_type=r.headers.get("content-type"))


if __name__ == "__main__":
    print(f"serving {NAME} on http://127.0.0.1:{a.port}  (non-chat calls forwarded to {a.ollama})")
    uvicorn.run(app, host="127.0.0.1", port=a.port)
